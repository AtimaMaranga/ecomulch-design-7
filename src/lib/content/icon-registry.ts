export const DEFAULT_ICON = "leaf";

/** Returns a resolvable icon component, falling back to the default. */
export function resolveIcon(name: string | undefined): AnyIcon {
  if (name && ICONS[name]) return ICONS[name];
  return ICONS[DEFAULT_ICON];
}

/** Options for the admin icon picker. */
export const ICON_OPTIONS: { value: string; label: string }[] = Object.keys(
  ICONS,
).map((value) => ({
  value,
  label: value.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
}));
